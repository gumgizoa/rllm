"""Build a training workflow's scored rubric from its generated rubric and its constraints.

    python -m recipe.grpo.qwen3_5.sdlc_if.build [--check] [WORKFLOW ...]    # no argument = the three

``reward/rubric.yaml`` stays the generator's output (``rubric.lock`` keeps checking it);
``reward/rubric.train.yaml`` is what the workflow's ``eval.py`` scores with: the generated items, changed
where ``constraints.yaml`` says the study's standard differs from the generator's reading. A constraint's
``change`` holds a ``reason`` and any of

    drop: true             the item is not scored (the constraint's status is ``dropped``)
    requirement: [a, b]    the generated level ``a`` becomes ``b`` (the constraint's ``requirement``)
    check: {kind, params}  replaces the generated check

``--check`` fails when a committed ``rubric.train.yaml`` differs from a fresh build.
"""

from __future__ import annotations

import argparse
import copy
import sys

import yaml

from .constraints import WORKFLOWS, load

TRAIN = ("agentos_v2", "openspec_ff", "speckit_bug")
HEADER = "# Generated by sdlc_if/build.py from rubric.yaml and ../constraints.yaml -- do not edit; see its docstring.\n"


def build(workflow: str) -> str:
    doc = load(workflow)
    gen = yaml.safe_load((WORKFLOWS / workflow / doc["generated"]).read_text())
    changes = {c["id"]: c["change"] for c in doc["constraints"] if c.get("change")}
    ids = {it["id"] for it in gen["items"]}
    unknown = sorted(set(changes) - ids)
    if unknown:
        raise SystemExit(f"{workflow}: changes for items the generated rubric lacks: {unknown[:5]}")
    items = []
    for it in gen["items"]:
        ch = changes.get(it["id"])
        if not ch:
            items.append(it)
            continue
        if not str(ch.get("reason") or "").strip():
            raise SystemExit(f"{workflow}: {it['id']}: change without a reason")
        if ch.get("drop"):
            continue
        it = copy.deepcopy(it)
        if "requirement" in ch:
            a, b = ch["requirement"]
            if it["requirement"] != a:
                raise SystemExit(f"{workflow}: {it['id']}: generated requirement {it['requirement']!r}, change says {a!r}")
            it["requirement"] = b
        if "check" in ch:
            it["check"] = copy.deepcopy(ch["check"])
        it["note"] = (f"{it.get('note') or ''} | SDLC IF standard: {ch['reason']}").lstrip(" |")
        items.append(it)
    return HEADER + yaml.safe_dump({**gen, "items": items}, sort_keys=False, allow_unicode=True, width=1 << 16)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("workflows", nargs="*", default=list(TRAIN))
    ap.add_argument("--check", action="store_true", help="fail if a committed rubric.train.yaml differs from a fresh build")
    a = ap.parse_args(argv)
    stale = []
    for wf in a.workflows:
        out = WORKFLOWS / wf / load(wf)["rubric"]
        text = build(wf)
        if a.check:
            if not out.is_file() or out.read_text() != text:
                stale.append(wf)
            continue
        out.write_text(text)
        print(f"wrote {out.relative_to(WORKFLOWS)} ({len(yaml.safe_load(text)['items'])} items)")
    if stale:
        print(f"stale: {stale}; run the build", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
