def _penalty_items(items: list[dict], docs: dict[str, Doc]) -> list[dict]:
    """The items of :data:`PENALTY`, appended after the scored items."""
    out = list(items)
    for stage, rule, doc, quotes, evidence, note in PENALTY:
        hits = [docs[doc].find(q) for q in quotes]
        if None in hits:
            raise SystemExit(f"{doc} no longer states the rule of the penalty item {rule}: {quotes[hits.index(None)][:60]!r}")
        files = rule.startswith("plan_files.")
        out.append(
            {
                "id": f"{NEW}.{stage}.penalty.{rule}",
                "scope": "specific",
                "class": "content" if files else "evidence",
                "stage": stage,
                "target": {"type": "artifact", "ref": "tasks", "state": "final"} if files else {"type": "action", "ref": "run", "state": "final"},
                "check": {"kind": f"{NEW}.penalty", "params": {"rule": rule}},
                "requirement": "must",
                "modality_evidence": evidence,
                "none_allowed": "-",
                "applies_when": None,
                "weight": 1.0,
                "gate": None,
                "availability": ["trace"],
                "sources": [{"doc": doc, "lines": list(h), "quote": q} for q, h in zip(quotes, hits, strict=True)],
                "impl_refs": [],
                "derived_by": "manual",
                "template": "",
                "log_only": True,
                "note": note,
            }
        )
    return out


def _params(it: dict, docs: dict[str, Doc], report: dict) -> None:
    p = it["check"].get("params") or {}
    kind = it["check"]["kind"]
    if kind == "cross_ref" and isinstance((p.get("right") or {}).get("literal"), list):
        p["right"]["literal"] = [x for x in p["right"]["literal"] if x not in CUT_SECTIONS]
    if kind == "no_template_residue":
        # a pattern that is a literal of agentos_v2's templates goes when this workflow's templates no longer have it;
        # the other patterns (fill marks and the like) are rules, not template text, and stay
        everything = " ".join(d.text for d in docs.values())
        kept = []
        for x in p.get("patterns", []):
            lit = ws(_unescape(x))
            if lit not in _v2_text() or lit in everything:
                kept.append(x)
                continue
            for old, new in REWORD:  # a placeholder whose wording changed here stays, in its new wording
                lit = lit.replace(old, new)
            if lit in everything:
                kept.append(re.escape(lit))
        report["residue_patterns_dropped"] += len(p.get("patterns", [])) - len(kept)
        p["patterns"] = kept
    if kind == "no_template_residue" and it.get("target", {}).get("ref") == "tasks":
        p["patterns"] += [re.escape(x) for x in TASKS_PLACEHOLDERS if re.escape(x) not in p["patterns"]]
    if p.get("section") == SUITE_OLD:
        p["section"] = SUITE_NEW
    if kind == f"{NEW}.report" and p.get("rule") in ("test_counts", "failed_listed", "suite_status"):
        p["suite_section"] = SUITE_NEW
        p["fix_round"] = True  # T6: after a return to PHASE 2 the report is about the re-run
