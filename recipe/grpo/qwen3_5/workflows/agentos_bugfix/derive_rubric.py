def _added(items: list[dict], docs: dict[str, Doc]) -> list[dict]:
    """The items of :data:`ADDED`, each a copy of its sibling with the new rule, put right after it."""
    for sibling, rule, params, quotes, evidence, note in ADDED:
        hits = [docs["IT"].find(q) for q in quotes]
        if None in hits:
            raise SystemExit(f"implement-tasks.md no longer states the rule of {rule}: {quotes[hits.index(None)][:60]!r}")
        at = next(n for n, it in enumerate(items) if it["id"].endswith(sibling))
        new = copy.deepcopy(items[at])
        new["id"] = new["id"].rsplit(".", 1)[0] + "." + rule
        new["check"]["params"] = {"rule": rule, **params}
        new["requirement"], new["weight"], new["derived_by"], new["log_only"] = "must", 1.0, "manual", False
        new["modality_evidence"] = evidence
        new["sources"] = [{"doc": "IT", "lines": list(h), "quote": q} for q, h in zip(quotes, hits, strict=True)]
        new["note"] = note
        items = items[: at + 1] + [new] + items[at + 1 :]
    return items


