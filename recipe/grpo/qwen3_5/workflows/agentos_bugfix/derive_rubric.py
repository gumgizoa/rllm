"""Derive ``reward/rubric.yaml`` of agentos_bugfix from agentos_v2's rubric.

    python -m recipe.grpo.qwen3_5.workflows.agentos_bugfix.derive_rubric            # write rubric.yaml + rubric.lock
    python -m recipe.grpo.qwen3_5.workflows.agentos_bugfix.derive_rubric --check    # exit 1 when they are stale

agentos_bugfix is agentos_v2 with steps cut (``build.py``, ``CHANGES.md``), so its verifier is agentos_v2's with
the items of those steps removed -- every other item is kept as it is, under this workflow's names. Nothing is
generated by a model here; the script is rerun whenever agentos_v2's rubric or this workflow's documents change.

1. names: ``agentos_v2`` -> ``agentos_bugfix`` (workflow, item ids, plugin kinds);
2. :data:`DROP`: the items of the cut steps; :data:`DROP_ARTIFACTS`: the folders no longer made;
3. parameters that name what was cut: allowed section lists, template placeholders that no longer exist in the
   documents, the report's test-results section (``3.`` -> ``2.``);
4. sources: each quote is looked up in this workflow's documents and its line numbers rewritten; a quote whose
   wording was made dataset-neutral is retried with the same replacements; a quote that is gone is dropped
   (listed in the lock);
5. the golden run (``selftest_golden.py``) is scored and the result recorded under ``generated.selftest``.
"""

