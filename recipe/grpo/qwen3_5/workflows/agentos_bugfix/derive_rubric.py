def ws(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


class Doc:
    """A document's text with whitespace collapsed, and the line each position came from."""

    def __init__(self, path: Path):
        self.sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
        self.raw = path.read_text(encoding="utf-8")
        self.text, self.line_at = "", []
        for no, line in enumerate(self.raw.split("\n"), 1):
            for tok in line.split():
                if self.text:
                    self.text += " "
                    self.line_at.append(no)
                self.text += tok
                self.line_at += [no] * len(tok)

    def find(self, quote: str) -> tuple[int, int] | None:
        """Lines of ``quote`` (``...`` may elide text between its parts, in order), or None."""
        parts = [p for p in re.split(r"\s*(?:\.\.\.|…)\s*", ws(quote)) if p]
        pos, first = 0, None
        for p in parts:
            i = self.text.find(p, pos)
            if i < 0:
                return None
            first = i if first is None else first
            pos = i + len(p)
        return (self.line_at[first], self.line_at[pos - 1]) if parts else None


_V2_TEXT: list[str] = []


def _v2_text() -> str:
    if not _V2_TEXT:
        _V2_TEXT.append(" ".join(ws(p.read_text(encoding="utf-8")) for p in sorted((V2 / "docs").rglob("*.md"))))
    return _V2_TEXT[0]


def _unescape(pattern: str) -> str:
    return re.sub(r"\\(.)", r"\1", pattern)


def derive() -> tuple[dict, dict]:
    """(rubric, report): the derived rubric as a dict and what was dropped / rewritten."""
    rub = yaml.safe_load((V2 / "reward" / "rubric.yaml").read_text(encoding="utf-8").replace(OLD, NEW))
    docs = {s["id"]: Doc(HERE / s["path"]) for s in rub["sources"]}
    report: dict = {"dropped_items": [], "dropped_sources": [], "items_without_source": [], "reworded_quotes": 0, "residue_patterns_dropped": 0}

    for s in rub["sources"]:
        s["sha256"] = docs[s["id"]].sha256
    for a in DROP_ARTIFACTS:
        rub["artifacts"].pop(a)
    for st in rub["stages"]:
        st["artifacts"] = [a for a in st.get("artifacts", []) if a not in DROP_ARTIFACTS]

    known = {it["id"] for it in rub["items"]}
    missing = sorted(f"{NEW}.{d}" for d in DROP if f"{NEW}.{d}" not in known)
    if missing:
        raise SystemExit(f"DROP names items agentos_v2's rubric does not have: {missing}")
    items = []
    for it in rub["items"]:
        if it["id"].removeprefix(NEW + ".") in DROP:
            report["dropped_items"].append(it["id"])
            continue
        if it.get("target", {}).get("ref") in DROP_ARTIFACTS:
            raise SystemExit(f"{it['id']} targets a removed artifact; add it to DROP")
        _params(it, docs, report)
        _sources(it, docs, report)
        if not it["sources"] and it["check"]["kind"] == "unimplemented":
            report["dropped_items"].append(it["id"])  # a statement without a check whose text was cut
            report["items_without_source"].remove(it["id"])
            continue
        items.append(it)
    rub["items"] = items

    for key, entries in (rub.get("appendix") or {}).items():  # the appendix cites documents too
        if isinstance(entries, list) and entries and all(isinstance(e, dict) and "quote" in e and "doc" in e for e in entries):
            kept = []
            for e in entries:
                hit = _locate(e, docs)
                e.pop("_reworded", None)
                if hit:
                    e["lines"] = list(hit)
                    kept.append(e)
            rub["appendix"][key] = kept
    ids = {it["id"] for it in items}
    for key, entries in (rub.get("appendix") or {}).items():  # ... and items by id
        if isinstance(entries, list) and entries and all(isinstance(e, str) for e in entries):
            rub["appendix"][key] = [e for e in entries if e in ids]
        elif isinstance(entries, list) and entries and all(isinstance(e, dict) and "id" in e and "quote" not in e for e in entries):
            rub["appendix"][key] = [e for e in entries if e["id"] in ids or not str(e["id"]).startswith(NEW + ".")]
    rub["generated"] = {
        **rub["generated"],
        "derived": {"from": f"workflows/{OLD}/reward/rubric.yaml", "by": "workflows/agentos_bugfix/derive_rubric.py",
                    "dropped_items": len(report["dropped_items"]), "kept_items": len(items)},
    }
    rub["generated"].pop("cache", None)
    return rub, report


def _params(it: dict, docs: dict[str, Doc], report: dict) -> None:
    p = it["check"].get("params") or {}
    kind = it["check"]["kind"]
    if kind == "cross_ref" and isinstance((p.get("right") or {}).get("literal"), list):
        p["right"]["literal"] = [x for x in p["right"]["literal"] if x not in CUT_SECTIONS]
    if kind == "no_template_residue":
        # a pattern that is a literal of agentos_v2's templates goes when this workflow's templates no longer have it;
        # the other patterns (fill marks and the like) are rules, not template text, and stay
        everything = " ".join(d.text for d in docs.values())
        kept = [x for x in p.get("patterns", []) if ws(_unescape(x)) not in _v2_text() or ws(_unescape(x)) in everything]
        report["residue_patterns_dropped"] += len(p.get("patterns", [])) - len(kept)
        p["patterns"] = kept
    if kind == "no_template_residue" and it.get("target", {}).get("ref") == "tasks":
        p["patterns"] += [re.escape(x) for x in TASKS_PLACEHOLDERS if re.escape(x) not in p["patterns"]]
    if p.get("section") == SUITE_OLD:
        p["section"] = SUITE_NEW
    if kind == f"{NEW}.report" and p.get("rule") in ("test_counts", "failed_listed", "suite_status"):
        p["suite_section"] = SUITE_NEW
    if "six" in (it.get("note") or "") and kind == "cross_ref":
        it["note"] = it["note"].replace("the template's six", "the template's four")


def _locate(src: dict, docs: dict[str, Doc]) -> tuple[int, int] | None:
    doc = docs[src["doc"]]
    hit = doc.find(src["quote"])
    if hit is None:
        quote = src["quote"].replace(SUITE_OLD, SUITE_NEW)
        for old, new in REWORD:
            quote = quote.replace(old, new)
        hit = doc.find(quote)
        if hit is not None:
            src["quote"] = quote
            src["_reworded"] = True
    return hit


def _sources(it: dict, docs: dict[str, Doc], report: dict) -> None:
    kept = []
    for src in it.get("sources") or []:
        hit = _locate(src, docs)
        if hit is None:
            report["dropped_sources"].append({"item": it["id"], "doc": src["doc"], "quote": src["quote"][:120]})
            continue
        if src.pop("_reworded", False):
            report["reworded_quotes"] += 1
        src["lines"] = list(hit)
        kept.append(src)
    if it.get("sources") and not kept:
        report["items_without_source"].append(it["id"])
    it["sources"] = kept


def selftest(rubric_path: Path) -> dict:
    """The golden run and its honest variants and mutations scored on the derived rubric."""
    from ...workflow_rubric import schema as S
    from ...workflow_rubric.generator import selftest as G
    from . import selftest_golden as golden

    rub = G.with_docs(S.load(rubric_path), HERE)
    th, _ = G.thresholds_of(rub)
    res = G.check(rub, golden.golden, thresholds=th, variants=golden.VARIANTS)
    return {
        "status": res["status"], "golden": res.get("golden"), "golden_signals": res.get("golden_signals"),
        "golden_failing": res.get("golden_failing"), "thresholds": th,
        "results": [{k: r.get(k) for k in ("mutation", "kind", "status", "compliance")} for r in res.get("results", [])],
        "failures": res.get("failures", []),
    }


def dump(rub: dict) -> str:
    return yaml.safe_dump(rub, sort_keys=False, allow_unicode=True, width=120)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the committed rubric.yaml instead of writing")
    args = ap.parse_args(argv)
    rub, report = derive()
    path = OUT / "rubric.yaml"
    if args.check:
        mine = {k: v for k, v in rub.items() if k != "generated"}
        theirs = {k: v for k, v in yaml.safe_load(path.read_text(encoding="utf-8")).items() if k != "generated"}
        if mine != theirs:
            print("rubric.yaml is stale: rerun derive_rubric.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(dump(rub), encoding="utf-8")
    st = selftest(path)
    rub["generated"]["selftest"] = st
    path.write_text(dump(rub), encoding="utf-8")
    lock = {
        "generator": "agentos_bugfix.derive_rubric (no model)",
        "derived_from": {"path": f"../{OLD}/reward/rubric.yaml", "sha256": hashlib.sha256((V2 / "reward" / "rubric.yaml").read_bytes()).hexdigest()},
        "rubric_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "sources": {s["path"]: s["sha256"] for s in rub["sources"]},
        "report": report,
    }
    (OUT / "rubric.lock").write_text(json.dumps(lock, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"items {len(rub['items'])} (dropped {len(report['dropped_items'])}), sources dropped {len(report['dropped_sources'])}, "
          f"quotes reworded {report['reworded_quotes']}, items without a source {len(report['items_without_source'])}, "
          f"residue patterns dropped {report['residue_patterns_dropped']}")
    print(f"selftest {st['status']}: golden {st['golden']}")
    for f in st["failures"][:12]:
        print("  ", f[:200])
    return 0 if st["status"] == "passed" else 1


if __name__ == "__main__":
    sys.exit(main())
